/**
 * Incident Investigation Report — HTML rendering layer.
 *
 * Receives computed IncidentReport and produces a complete HTML page.
 * This module has NO business logic — only presentation.
 *
 * @module incident-report-renderer
 */

import { rootLogger } from '../logger.js';
import { sanitizeHtml } from '../escape.js';
import { buildHtmlPage, buildErrorPage } from './html-factory.js';
import { buildCss } from './report-styles.js';
import { MetricCard, MetricGrid, Card, Section, EmptyState } from '../primitives/index.js';
import { extractErrorMessage } from '../ui/prompt-errors.js';
import type { IncidentReport } from './incident-report.js';

function severityToCardSeverity(s: string): 'error' | 'warn' | 'info' | 'default' {
    if (s === 'high') return 'error';
    if (s === 'medium') return 'warn';
    if (s === 'low') return 'info';
    return 'default';
}

export function generateIncidentReportHtml(report: IncidentReport | null | undefined, title?: string): string {
    try {
        if (!report) {
            rootLogger.error(
                'Incident report is null or undefined. Ensure a valid IncidentReport object is passed to generateIncidentReportHtml.',
            );
            return buildErrorPage('Error generating report', 'Error generating incident investigation report');
        }

        const pageTitle = title || 'Incident Investigation Report';

        const bodyContent = wrapContainer(
            pageTitle,
            SeverityBanner(report.overallSeverity) +
                buildMetricSummary(report) +
                buildSummary(report) +
                buildEvents(report),
        );

        return buildHtmlPage({
            title: pageTitle,
            styles: buildCss(),
            theme: 'system',
            bodyContent,
            footer: 'Generated by QA Tools — Incident Investigation Report',
        });
    } catch (err: unknown) {
        rootLogger.error(
            'Failed to generate incident report HTML: ' +
                extractErrorMessage(err) +
                '. Verify that input data (failRate, passRate, regressionCount) is valid and the html-factory module is working correctly.',
        );
        return buildErrorPage('Error generating report', 'Error generating incident investigation report');
    }
}

function wrapContainer(pageTitle: string, children: string): string {
    return `<div data-component="container" data-dashboard="incident-report">
        <h1>${sanitizeHtml(pageTitle)}</h1>
        ${children}
    </div>`;
}

function SeverityBanner(severity: string): string {
    return `<div data-component="severity-banner">
        Overall Severity: ${sanitizeHtml(severity.toUpperCase())}
    </div>`;
}

function buildMetricSummary(report: IncidentReport): string {
    return Section({
        dataSection: 'summary',
        children: MetricGrid({
            children:
                MetricCard({ label: 'Total Events', value: String(report.eventCount) }) +
                MetricCard({
                    label: 'High',
                    value: String(report.highCount),
                    severity: report.highCount > 0 ? 'error' : 'default',
                }) +
                MetricCard({
                    label: 'Medium',
                    value: String(report.mediumCount),
                    severity: report.mediumCount > 0 ? 'warn' : 'default',
                }) +
                MetricCard({
                    label: 'Low',
                    value: String(report.lowCount),
                    severity: report.lowCount > 0 ? 'info' : 'default',
                }),
        }),
    });
}

function buildSummary(report: IncidentReport): string {
    return `<p data-part="summary">${sanitizeHtml(report.summary)}</p>`;
}

function buildEvents(report: IncidentReport): string {
    if (report.events.length === 0) {
        return EmptyState({
            title: 'No incidents to display',
            description: 'The incident report contains no events. This may indicate no recent failures were detected.',
            action: 'Verify that the test suite is running and failures are being captured by the monitoring pipeline.',
        });
    }

    return Section({
        dataSection: 'events',
        title: 'Events',
        children: report.events
            .map((event) =>
                Card({
                    severity: severityToCardSeverity(event.severity),
                    children:
                        `<div data-part="event-date">${sanitizeHtml(event.date)}</div>` +
                        `<div data-part="event-title">${sanitizeHtml(event.title)}</div>` +
                        `<div data-part="event-description">${sanitizeHtml(event.description)}</div>`,
                }),
            )
            .join(''),
    });
}
